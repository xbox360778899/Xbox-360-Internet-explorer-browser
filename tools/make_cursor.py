"""Generate the browser pointer icons from a vector polygon using Pillow."""
from pathlib import Path
from PIL import Image,ImageDraw,ImageFilter
root=Path(__file__).parents[1]
points=[(4,2),(4,30),(11,24),(17,38),(24,35),(18,22),(29,22)]
arrays=[]
for name,color in [('normal','#f7fbfc'),('hover','#ff5a8a')]:
    scale=4
    image=Image.new('RGBA',(40*scale,46*scale))
    shadow=Image.new('RGBA',image.size)
    ImageDraw.Draw(shadow).polygon([((x+2)*scale,(y+3)*scale) for x,y in points],fill=(0,0,0,150))
    image.alpha_composite(shadow.filter(ImageFilter.GaussianBlur(2*scale)))
    draw=ImageDraw.Draw(image)
    shape=[(x*scale,y*scale) for x,y in points]
    draw.polygon(shape,fill=color)
    draw.line(shape+[shape[0]],fill='#102025',width=2*scale,joint='curve')
    image=image.resize((40,46),Image.Resampling.LANCZOS)
    (root/'assets').mkdir(exist_ok=True)
    image.save(root/f'assets/cursor-{name}.png')
    rgb=[(r<<16)|(g<<8)|b for r,g,b,a in image.getdata()]
    alpha=[a for r,g,b,a in image.getdata()]
    arrays.append('static const uint32_t cursor_'+name+'_rgb[]={'+','.join(hex(v) for v in rgb)+'};')
    arrays.append('static const unsigned char cursor_'+name+'_alpha[]={'+','.join(str(v) for v in alpha)+'};')
    arrays.append('static const xui_sprite_t cursor_'+name+'={cursor_'+name+'_rgb,cursor_'+name+'_alpha,40,46};')
(root/'src/cursor_icon.h').write_text('// Generated by tools/make_cursor.py. Original vector pointer artwork.\n#pragma once\n'+'\n'.join(arrays))
print('Cursor icon assets generated.')
